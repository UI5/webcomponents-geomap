function toFeature(country) {
	return {
		type: "Feature",
		geometry: { type: "Polygon", coordinates: [country.coords] },
		properties: {},
	};
}

// ── Shape features ────────────────────────────────────────────────────────────

function createCirclePolygon(centerLng, centerLat, radiusKm, steps = 64) {
	const round = (v) => Math.round(v * 1e5) / 1e5;
	const ring = [];
	for (let i = 0; i < steps; i++) {
		const angle = (i / steps) * Math.PI * 2;
		const dLat = radiusKm / 110.574;
		const dLng = radiusKm / (111.32 * Math.cos((centerLat * Math.PI) / 180));
		ring.push([
			round(centerLng + (dLng * Math.cos(angle))),
			round(centerLat + (dLat * Math.sin(angle))),
		]);
	}
	ring.push([ring[0][0], ring[0][1]]);
	return ring;
}

