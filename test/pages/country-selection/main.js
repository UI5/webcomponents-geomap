// ── State helpers ─────────────────────────────────────────────────────────────

// Which source is driving the current selection: "countries" | "shape" | null
let activeSource = null;

function clearCountryButtons() {
	Object.keys(countries).forEach(key => {
		document.getElementById(`btn-${key}`).pressed = false;
	});
}

function updateStatus() {
	const features = map.getSelection();
	if (!features.length) {
		status.textContent = "No selection";
		return;
	}

	if (activeSource === "countries") {
		const pressed = Object.keys(countries).filter(key =>
			document.getElementById(`btn-${key}`).pressed
		);
		status.textContent = `Countries: ${pressed.map(k => countries[k].label).join(", ")}`;
	} else {
		status.textContent = `${features.length} feature(s): ${features.map(f => f.geometry.type).join(", ")}`;
	}
}

function clearAll() {
	map.removeSelection();
	clearCountryButtons();
	activeSource = null;
	updateStatus();
}

// ── Country buttons ───────────────────────────────────────────────────────────

Object.keys(countries).forEach(key => {
	document.getElementById(`btn-${key}`).addEventListener("click", () => {
		// ui5-toggle-button updates `pressed` after the click event fires
		Promise.resolve().then(() => {
			const btn = document.getElementById(`btn-${key}`);
			if (btn.pressed) {
				// Depress all other country buttons (single-select)
				Object.keys(countries).forEach(k => {
					if (k !== key) document.getElementById(`btn-${k}`).pressed = false;
				});
				activeSource = "countries";
				map.setSelection(toFeature(countries[key]));
			} else {
				map.removeSelection();
				activeSource = null;
			}
			updateStatus();
		});
	});
});

