/**
 * Selection mode buttons available in the `ui5-geomap-selection-control`.
 *
 * @public
 */
enum GeomapSelectionMode {
	/**
	 * Freehand drawing tool.
	 * @public
	 */
	Freehand = "freehand",
	/**
	 * Polygon drawing tool.
	 * @public
	 */
	Polygon = "polygon",
	/**
	 * Rectangle drawing tool.
	 * @public
	 */
	Rectangle = "rectangle",
	/**
	 * Circle drawing tool.
	 * @public
	 */
	Circle = "circle",
	/**
	 * Selection (cursor) tool.
	 * @public
	 */
	Select = "select",
}

export default GeomapSelectionMode;
